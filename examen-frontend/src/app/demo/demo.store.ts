interface DemoState {
  version: 1;
  nextId: number;
  categories: Category[];
  questions: Question[];
  journal: JournalEntry[];
  todos: Todo[];
  sessions: SessionSummary[];
  gratitude: GratitudeEntry[];
  habits: HabitScoreEntry[];
  notifications: NotificationItem[];
  feedback: InsightFeedbackResponse[];
  settings: UserSettingsResponse;
}

function dateAgo(days: number): string {
  const date = new Date();
  date.setDate(date.getDate() - days);
  return date.toISOString();
}

function seed(): DemoState {
  const categories = ['Relish', 'Request', 'Review', 'Repent', 'Resolve'].map((name, i) => ({
    id: i + 1, name, description: `The ${name.toLowerCase()} movement of daily reflection.`
  }));
  const prompts = [
    'What small gift am I grateful for today?', 'Where did I ask for clarity today?',
    'When did I make time to listen?', 'What could I meet with more patience?',
    'What kind action will I take tomorrow?'
  ];
  return {
    version: 1, nextId: 100,
    categories,
    questions: prompts.map((text, i) => ({ id: i + 1, text, orderNumber: i + 1,
      responseType: 'SCALE_1_5', category: categories[i], custom: false, defaultQuestion: true })),
    journal: [{ id: 20, content: 'A sample reflection: slowing down helped me notice a small kindness today.', createdAt: dateAgo(2) }],
    todos: [{ id: 30, title: 'Take a quiet walk', completed: false, dueAt: dateAgo(0) },
      { id: 31, title: 'Thank someone who helped', completed: true, dueAt: dateAgo(1) }],
    sessions: [2, 3, 4, 6, 8].map((days, i) => ({ id: 40 + i, userId: 1,
      startedAt: dateAgo(days), completedAt: dateAgo(days), notes: 'Sample reflection: choose patience and notice gratitude.',
      moodScore: i % 2 + 3, score: 75, answers: [] })),
    gratitude: [{ id: 60, content: 'A thoughtful conversation with a friend (sample)', createdAt: dateAgo(2) }],
    habits: [{ id: 70, habit: 'Quiet reflection', score: 4, scoreDate: dateAgo(2).slice(0, 10) }],
    notifications: [{ id: 80, title: 'Welcome to the demo', message: 'Explore with sample data. Reset anytime using the demo banner.',
      type: 'INFO', createdAt: dateAgo(0), readAt: null }],
    feedback: [],
    settings: { timeZone: Intl.DateTimeFormat().resolvedOptions().timeZone || 'UTC', reminderTime: '20:00',
      theme: 'system', emailReminder: false, inAppReminder: false }
  };
}

@Injectable({ providedIn: 'root' })
export class DemoStore {
  private state: DemoState;

  constructor(private storage: LocalStorageService) {
    try {
      const saved = JSON.parse(storage.get('data') || 'null') as DemoState | null;
      this.state = saved?.version === 1 ? saved : seed();
    } catch { this.state = seed(); }
  }

  handle(request: HttpRequest<unknown>): unknown {
    const url = new URL(request.urlWithParams, 'https://demo.invalid');
    if (!url.pathname.startsWith('/demo-api/')) this.fail('Demo network requests are disabled.', 403);
    const path = url.pathname.slice('/demo-api/'.length);
    const method = request.method;
    // Payloads are generated by the existing typed application services.
    const body = (request.body || {}) as Record<string, unknown>;
    const result = this.respond(path, method, body, url.searchParams);
    if (method !== 'GET') this.storage.set('data', JSON.stringify(this.state));
    return result;
  }

  private respond(path: string, method: string, body: Record<string, unknown>, params: URLSearchParams): unknown {
    const s = this.state;
    const now = new Date().toISOString();
    const completed = s.sessions.filter(item => item.completedAt);
    const inDays = (days: number) => completed.filter(item => new Date(item.completedAt!).getTime() >= Date.now() - days * 86400000);
    const mean = (values: number[]) => values.length ? values.reduce((a, b) => a + b, 0) / values.length : null;
    const mood = mean(completed.map(item => item.moodScore || 3));
    const period = (days: number) => ({ period: days === 7 ? 'week' : 'month', sessions: inDays(days).length,
      completedDays: new Set(inDays(days).map(item => item.completedAt!.slice(0, 10))).size,
      averageMood: mean(inDays(days).map(item => item.moodScore || 3)) });
    const summary = { summary: 'Sample insight: make space for gratitude and one small kind action.', highlights: ['These are local demo suggestions, with no AI processing.'],
      periodDays: Number(params.get('days') || 30), sessionsCompleted: completed.length, averageFeeling: mood, generatedAt: now };

    if (path === 'auth/login' || path === 'auth/register') return { userId: 1, fullName: 'Demo Visitor', email: 'visitor@example.invalid', token: 'local-demo' };
    if (path.startsWith('auth/reset/')) this.fail('Password recovery is unavailable in this demo. No email is sent.', 400);
    if (path === 'settings') {
      if (method === 'PUT') s.settings = { ...s.settings, ...body, emailReminder: false, inAppReminder: false };
      return s.settings;
    }
    if (path === 'users/me/export') return new Blob([JSON.stringify(s, null, 2)], { type: 'application/json' });
    if (path === 'users/me/delete') { this.state = seed(); this.storage.clear(); return null; }
    if (path === 'sessions/active') return s.sessions.find(item => !item.completedAt) || null;
    if (path === 'sessions/start') {
      const active = s.sessions.find(item => !item.completedAt);
      if (active) return active;
      const session = { id: s.nextId++, userId: 1, startedAt: now, answers: [] };
      s.sessions.unshift(session); return session;
    }
    if (path === 'sessions/me') return this.page([...completed].sort((a, b) => b.completedAt!.localeCompare(a.completedAt!)), params);
    const submit = path.match(/^sessions\/(\d+)\/submit$/);
    if (submit) {
      const session = s.sessions.find(item => item.id === Number(submit[1]));
      if (!session) this.fail('Session not found.');
      Object.assign(session!, body, { completedAt: now, score: 80 }); return session;
    }
    if (path === 'profile/summary') return {
      examinationsCompleted: completed.length, todosCompleted: s.todos.filter(item => item.completed).length,
      categoriesUsed: s.categories.length, streakDays: this.streak(completed), spiritualProgressScore: mean(completed.map(item => item.score || 0)),
      averageMoodLast30Days: period(30).averageMood, todayMood: completed.find(item => item.completedAt!.slice(0, 10) === now.slice(0, 10))?.moodScore ?? null,
      sessionsThisWeek: inDays(7).length, sessionsThisMonth: inDays(30).length,
      todayCompleted: completed.some(item => item.completedAt!.slice(0, 10) === now.slice(0, 10)),
      recentMoodTrend: completed.map(item => ({ date: item.completedAt!.slice(0, 10), mood: item.moodScore }))
    };
    if (path === 'profile/progress') return { points: Array.from({ length: Math.min(90, Number(params.get('days') || 14)) }, (_, i) => {
      const date = dateAgo(i).slice(0, 10); const session = completed.find(item => item.completedAt!.slice(0, 10) === date);
      return { date, completed: !!session, mood: session?.moodScore ?? null };
    }).reverse() };
    if (path === 'profile/summary/weekly') return period(7);
    if (path === 'profile/summary/monthly') return period(30);
    if (path === 'profile/analytics') return { overallAverageScore: mean(completed.map(item => item.score || 0)), overallMood: mood, categories: [],
      weeklyTrend: [0, 7, 14, 21].map(days => ({ weekStart: dateAgo(days + 7).slice(0, 10),
        sessions: inDays(days + 7).length - inDays(days).length, averageMood: mood })).reverse() };
    if (path === 'growth/weekly-summary') return { sessionsCompleted: inDays(7).length, todosCompleted: s.todos.filter(item => item.completed).length,
      habitsScored: s.habits.length, averageHabitScore: mean(s.habits.map(item => item.score)) || 0, gratitudeCount: s.gratitude.length };
    if (path === 'growth/meditation-suggestions') return ['Take five quiet breaths.', 'Notice one small kindness.', 'Choose a kind action for tomorrow.'];
    if (path === 'growth/export/pdf') this.fail('PDF export is available in the self-hosted app. Use Settings to download demo data as JSON.', 400);
    if (path === 'insights/summary') return summary;
    if (path === 'insights/questions') return { focus: body['focus'], suggestions: [`Where did I practice ${String(body['focus'] || 'gratitude').slice(0, 80)} today?`], followUps: [], generatedAt: now };
    if (path === 'insights/follow-ups') return [{ question: 'What small act of kindness could I repeat tomorrow?', rationale: 'A local sample prompt.', sourceContext: 'Demo', generatedAt: now }];
    if (path === 'insights/session') return { sessionId: body['sessionId'], summary: summary.summary, insights: summary.highlights,
      nextSteps: ['Choose one kind action tomorrow.'], averageFeeling: mood, generatedAt: now };
    if (/^insights\/sessions\/\d+\/(tag|tags)$/.test(path)) return [];
    if (path === 'insights/tags/summary') return { periodDays: 30, totalTags: 0, virtues: [], struggles: [], gratitude: [], stressors: [], generatedAt: now };
    if (path === 'insights/weekly-narrative') return { title: 'Sample weekly reflection', narrative: summary.summary, periodStart: dateAgo(7).slice(0, 10),
      periodEnd: now.slice(0, 10), sessionsAnalyzed: inDays(7).length, averageFeeling: mood, virtuesObserved: [], strugglesIdentified: [],
      gratitudeThemes: [], stressorSignals: [], actionableAdvice: ['Make time for a quiet reflection.'], generatedAt: now };
    if (path === 'insights/feedback') return this.collection(s.feedback, '', method, body, { createdAt: now });
    if (path === 'journal') return this.collection(s.journal, '', method, body, { createdAt: now });
    if (path === 'growth/gratitude') return this.collection(s.gratitude, '', method, body, { createdAt: now });
    if (path === 'growth/habits') return this.collection(s.habits, '', method, body, { scoreDate: now.slice(0, 10) });
    if (path === 'notifications') return params.get('unreadOnly') === 'true' ? s.notifications.filter(item => !item.readAt) : s.notifications;
    const read = path.match(/^notifications\/(\d+)\/read$/);
    if (read) { const item = s.notifications.find(item => item.id === Number(read[1])); if (item) item.readAt = now; return null; }
    if (path.startsWith('todos')) return this.collection(s.todos, path.slice('todos'.length).replace(/^\//, ''), method, body, { completed: false, dueAt: now });
    if (path === 'categories' && method === 'GET') return this.page(s.categories, params);
    if (path.startsWith('categories')) {
      const suffix = path.slice('categories'.length).replace(/^\//, '');
      if (method === 'DELETE') s.questions = s.questions.filter(item => item.category.id !== Number(suffix));
      const result = this.collection(s.categories, suffix, method, body);
      s.questions.forEach(item => { item.category = s.categories.find(category => category.id === item.category.id) || item.category; });
      return result;
    }
    if (path === 'questions' && method === 'GET') return this.page(s.questions, params);
    if (path === 'questions/my') return s.questions.filter(item => item.custom);
    const category = path.match(/^questions\/category\/(\d+)$/);
    if (category) return s.questions.filter(item => item.category.id === Number(category[1]));
    if (path.startsWith('questions/')) {
      const suffix = path.replace(/^questions\/(custom\/?|)/, '');
      if (method !== 'DELETE') {
        const category = s.categories.find(item => item.id === Number(body['categoryId']));
        if (!category) this.fail('Choose a category.', 400);
        body = { ...body, category, custom: true, defaultQuestion: false };
      }
      return this.collection(s.questions, suffix, method, body);
    }
    this.fail(`Unsupported demo operation: ${method} ${path}`);
  }

  private collection<T extends { id?: number }>(items: T[], suffix: string, method: string,
    body: Record<string, unknown>, defaults: Record<string, unknown> = {}): unknown {
    if (!suffix) {
      if (method === 'GET') return items;
      if (method === 'POST') { const item = { ...defaults, ...body, id: this.state.nextId++ } as unknown as T; items.unshift(item); return item; }
    }
    const id = Number(suffix.split('/')[0]);
    const index = items.findIndex(item => item.id === id);
    if (index < 0) this.fail('Demo item not found.');
    if (method === 'DELETE') { items.splice(index, 1); return null; }
    if (method === 'GET') return items[index];
    if (method === 'PATCH' || method === 'PUT') {
      const changes = suffix.endsWith('/toggle') ? { completed: !(items[index] as unknown as Todo).completed } : body;
      items[index] = { ...items[index], ...changes, id }; return items[index];
    }
    this.fail('Unsupported demo operation.', 405);
  }

  private page<T>(items: T[], params: URLSearchParams): unknown {
    const size = Math.max(1, Number(params.get('size') || 200));
    const page = Math.max(0, Number(params.get('page') || 0));
    return { content: items.slice(page * size, (page + 1) * size), totalElements: items.length,
      totalPages: Math.ceil(items.length / size), number: page, size };
  }

  private streak(sessions: SessionSummary[]): number {
    const dates = new Set(sessions.map(item => item.completedAt!.slice(0, 10)));
    let offset = dates.has(dateAgo(0).slice(0, 10)) ? 0 : 1;
    let count = 0;
    while (dates.has(dateAgo(offset++).slice(0, 10))) count++;
    return count;
  }

  private fail(message: string, status = 404): never {
    throw new HttpErrorResponse({ status, error: { message } });
  }
}
