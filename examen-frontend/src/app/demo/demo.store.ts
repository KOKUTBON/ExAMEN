import { Injectable } from '@angular/core';
import { HttpErrorResponse, HttpRequest } from '@angular/common/http';
import { LocalStorageService } from '../core/services/local-storage.service';
import { Category } from '../core/services/category.service';
import { Question } from '../core/services/question.service';
import { JournalEntry } from '../core/services/journal.service';
import { Todo } from '../shared/features/todos/services/todo.service';
import { SessionSummary } from '../shared/features/examination/models/examination.model';
import { GratitudeEntry, HabitScoreEntry } from '../shared/features/profile/services/growth.service';
